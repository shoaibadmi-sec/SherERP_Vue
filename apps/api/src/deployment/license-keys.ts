import type { ApiConfig } from '../config';

/**
 * The public keys this build trusts to have signed a licence (D-35).
 *
 * **The private halves are not here, and never will be.** They live on the
 * vendor's own machine, outside this repository, outside every database and
 * outside every customer install — `tools/licence` generates them and is the
 * only thing that ever holds one. What ships to a shop is the verifying half,
 * which can check a licence and could not forge one.
 *
 * **Why a list rather than one key.** A signing key that can never be replaced
 * is a signing key that can never be *rotated*, and the day one has to be
 * retired is not the day to invent a mechanism. Every licence names the key
 * that signed it (`signing_key_id`), so a new key can be added here, issued
 * against, and the old one left in place until the last licence signed by it
 * has expired.
 */
export interface TrustedLicenseKey {
  readonly id: string;
  /** Ed25519 public key, base64 of the SPKI DER encoding. */
  readonly publicKeyBase64: string;
  /**
   * A development key, generated by whoever is working on SherERP.
   *
   * Two things follow from it, and only these two: a licence it signed may name
   * `*` as its business, so one key covers a developer's many test businesses;
   * and it is configured rather than embedded, so it exists on no customer
   * machine. A production build with no `LICENSE_TRUSTED_KEYS` set trusts
   * nothing marked this way, because nothing marked this way is present.
   */
  readonly dev: boolean;
}

/**
 * The production verifying key, embedded at package time.
 *
 * Empty in the repository on purpose (this is unchanged from Phase 1.7): a
 * placeholder that *looked* like a key would mean a build that appears to
 * validate licences and does not. `pnpm licence:keygen` prints the line to put
 * here when the vendor's production key is created.
 */
const EMBEDDED_KEYS: readonly TrustedLicenseKey[] = [];

/**
 * Every key this deployment will accept: what the build embeds, plus what its
 * configuration adds.
 *
 * `LICENSE_TRUSTED_KEYS` is `id|base64[|dev]`, comma-separated. Base64 contains
 * neither `|` nor `,`, so no escaping question arises. `LICENSE_PUBLIC_KEY` is
 * still honoured as the single unnamed key Phase 1.7 defined, so an install
 * configured before licence ids existed keeps working.
 */
export function trustedLicenseKeys(config: ApiConfig): readonly TrustedLicenseKey[] {
  const keys: TrustedLicenseKey[] = [...EMBEDDED_KEYS];

  if (config.licensePublicKey !== '') {
    keys.push({ id: LEGACY_KEY_ID, publicKeyBase64: config.licensePublicKey, dev: false });
  }

  for (const entry of config.licenseTrustedKeys.split(',')) {
    const parts = entry.split('|').map((part) => part.trim());
    const [id, publicKeyBase64, marker] = parts;
    if (id === undefined || id === '') continue;
    if (publicKeyBase64 === undefined || publicKeyBase64 === '') continue;
    keys.push({ id, publicKeyBase64, dev: marker === 'dev' });
  }

  return keys;
}

/** What a key configured through the Phase 1.7 single-key setting is called. */
export const LEGACY_KEY_ID = 'sher-1';
