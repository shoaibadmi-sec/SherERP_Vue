import type { CallHandler, ExecutionContext, NestInterceptor } from '@nestjs/common';
import { Inject, Injectable } from '@nestjs/common';
import type { RecordPermissionDenialService, TenantContext } from '@sher/core-application';
import { AppError, ErrorCode } from '@sher/core-contracts';
import type { Request, Response } from 'express';
import type { Observable } from 'rxjs';
import { catchError, from, switchMap, throwError } from 'rxjs';

import { RECORD_PERMISSION_DENIAL_SERVICE } from '../audit/tokens';
import { TRACE_ID_HEADER } from './trace-id.middleware';

interface RequestWithContext extends Request {
  tenantContext?: TenantContext;
}

/** GET and HEAD read; everything else mutates (§5.22 audits only the latter). */
const READ_METHODS = new Set(['GET', 'HEAD', 'OPTIONS']);

/**
 * Writes the §5.22 audit row when a mutating request is refused for want of a
 * permission.
 *
 * Infrastructure, not a business rule: it decides *nothing* about the refusal,
 * which has already been made and thrown by the use case. It observes that a
 * refusal happened, and hands the facts to the application service that records
 * it. The decision of what a denial row contains lives there (R-B1).
 *
 * **Read denials are skipped** — §5.22 wants those "in aggregate only", and a
 * row per refused page view would bury the mutation attempts that matter inside
 * noise generated by ordinary navigation.
 *
 * The refusal is re-thrown unchanged whether or not recording worked. A failure
 * to write the trail must not turn a correct 403 into a 500.
 */
@Injectable()
export class DenialAuditInterceptor implements NestInterceptor {
  constructor(
    @Inject(RECORD_PERMISSION_DENIAL_SERVICE)
    private readonly denials: RecordPermissionDenialService,
  ) {}

  intercept(context: ExecutionContext, next: CallHandler): Observable<unknown> {
    const http = context.switchToHttp();
    const request = http.getRequest<RequestWithContext>();

    return next.handle().pipe(
      // The recording is **awaited** before the refusal is re-thrown. Firing it
      // off unawaited would send the 403 while the evidence was still in
      // flight, so a process that died in between would refuse the caller and
      // record nothing — and §5.22 wants the attempt on record. The cost is one
      // short transaction on a request that has already failed.
      catchError((cause: unknown) =>
        from(this.recordIfDenial(cause, request, http.getResponse<Response>())).pipe(
          switchMap(() => throwError(() => cause)),
        ),
      ),
    );
  }

  private async recordIfDenial(
    cause: unknown,
    request: RequestWithContext,
    response: Response,
  ): Promise<void> {
    if (!(cause instanceof AppError) || cause.code !== ErrorCode.PERMISSION_DENIED) return;
    if (READ_METHODS.has(request.method)) return;

    // No verified context means the caller was never identified, so there is no
    // tenant to file the row under and no user to name in it.
    const ctx = request.tenantContext;
    if (ctx === undefined) return;

    try {
      await this.denials.record({
        ctx,
        permissionCode: cause.details?.['permission'] ?? 'unknown',
        resource: `${request.method} ${request.originalUrl}`,
        traceId: response.getHeader(TRACE_ID_HEADER)?.toString() ?? '',
      });
    } catch (recordingFailed) {
      // Deliberately swallowed — see RecordPermissionDenialService. Written to
      // stderr so a broken audit path is still discoverable in the logs.
      process.stderr.write(`failed to record permission denial: ${describe(recordingFailed)}\n`);
    }
  }
}

function describe(cause: unknown): string {
  return cause instanceof Error ? (cause.stack ?? cause.message) : String(cause);
}
