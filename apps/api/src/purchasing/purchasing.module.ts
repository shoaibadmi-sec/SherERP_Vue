import { Module } from '@nestjs/common';
import type {
  AccessControl,
  AuditWriter,
  DocumentReversalRepository,
  IdempotencyStore,
  InventoryRepository,
  MoneyRepository,
  NumberingService,
  Outbox,
  PartyRepository,
  PeriodGuard,
  ProductRepository,
  PurchaseRepository,
  LandedCostRepository,
  PurchasePlanRepository,
  SaleRepository,
  SettingsRepository,
  UnitOfWork,
} from '@sher/core-application';
import {
  AddLandedCostService,
  CreatePurchaseService,
  PaySupplierService,
  PlannerService,
  PurchasePlanService,
  PurchaseQueryService,
  VoidPurchaseService,
} from '@sher/core-application';
import type { Clock } from '@sher/shared-utils';

import {
  ACCESS_CONTROL,
  AUDIT_WRITER,
  DOCUMENT_REVERSAL_REPOSITORY,
  CLOCK,
  IDEMPOTENCY_STORE,
  INVENTORY_REPOSITORY,
  MONEY_REPOSITORY,
  NUMBERING_SERVICE,
  OUTBOX,
  PARTY_REPOSITORY,
  PERIOD_GUARD,
  PRODUCT_REPOSITORY,
  PURCHASE_REPOSITORY,
  PURCHASE_PLAN_REPOSITORY,
  LANDED_COST_REPOSITORY,
  SALE_REPOSITORY,
  SETTINGS_REPOSITORY,
  UNIT_OF_WORK,
} from '../infrastructure/tokens';
import {
  LandedCostsController,
  PurchasePlansController,
  SupplierOrdersController,
} from './purchase-plans.controller';
import { PurchasesController } from './purchases.controller';
import { SupplierPaymentsController } from './supplier-payments.controller';
import {
  ADD_LANDED_COST_SERVICE,
  CREATE_PURCHASE_SERVICE,
  VOID_PURCHASE_SERVICE,
  PAY_SUPPLIER_SERVICE,
  PLANNER_SERVICE,
  PURCHASE_PLAN_SERVICE,
  PURCHASE_QUERY_SERVICE,
} from './tokens';

/** Phase 5 — buying goods, and paying the supplier for them (§5.9). */
@Module({
  controllers: [
    PurchasesController,
    SupplierPaymentsController,
    PurchasePlansController,
    SupplierOrdersController,
    LandedCostsController,
  ],
  providers: [
    {
      provide: CREATE_PURCHASE_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        idempotency: IdempotencyStore,
        periods: PeriodGuard,
        parties: PartyRepository,
        products: ProductRepository,
        inventory: InventoryRepository,
        money: MoneyRepository,
        purchases: PurchaseRepository,
        numbering: NumberingService,
        audit: AuditWriter,
        outbox: Outbox,
        clock: Clock,
      ): CreatePurchaseService =>
        new CreatePurchaseService(
          uow,
          accessControl,
          idempotency,
          periods,
          parties,
          products,
          inventory,
          money,
          purchases,
          numbering,
          audit,
          outbox,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        ACCESS_CONTROL,
        IDEMPOTENCY_STORE,
        PERIOD_GUARD,
        PARTY_REPOSITORY,
        PRODUCT_REPOSITORY,
        INVENTORY_REPOSITORY,
        MONEY_REPOSITORY,
        PURCHASE_REPOSITORY,
        NUMBERING_SERVICE,
        AUDIT_WRITER,
        OUTBOX,
        CLOCK,
      ],
    },
    {
      provide: PAY_SUPPLIER_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        idempotency: IdempotencyStore,
        periods: PeriodGuard,
        parties: PartyRepository,
        money: MoneyRepository,
        purchases: PurchaseRepository,
        reversals: DocumentReversalRepository,
        numbering: NumberingService,
        audit: AuditWriter,
        outbox: Outbox,
        clock: Clock,
      ): PaySupplierService =>
        new PaySupplierService(
          uow,
          accessControl,
          idempotency,
          periods,
          parties,
          money,
          purchases,
          reversals,
          numbering,
          audit,
          outbox,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        ACCESS_CONTROL,
        IDEMPOTENCY_STORE,
        PERIOD_GUARD,
        PARTY_REPOSITORY,
        MONEY_REPOSITORY,
        PURCHASE_REPOSITORY,
        DOCUMENT_REVERSAL_REPOSITORY,
        NUMBERING_SERVICE,
        AUDIT_WRITER,
        OUTBOX,
        CLOCK,
      ],
    },
    {
      provide: PURCHASE_QUERY_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        purchases: PurchaseRepository,
        clock: Clock,
      ): PurchaseQueryService => new PurchaseQueryService(uow, accessControl, purchases, clock),
      inject: [UNIT_OF_WORK, ACCESS_CONTROL, PURCHASE_REPOSITORY, CLOCK],
    },
    {
      provide: VOID_PURCHASE_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        periods: PeriodGuard,
        inventory: InventoryRepository,
        purchases: PurchaseRepository,
        audit: AuditWriter,
        outbox: Outbox,
        clock: Clock,
      ): VoidPurchaseService =>
        new VoidPurchaseService(
          uow,
          accessControl,
          periods,
          inventory,
          purchases,
          audit,
          outbox,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        ACCESS_CONTROL,
        PERIOD_GUARD,
        INVENTORY_REPOSITORY,
        PURCHASE_REPOSITORY,
        AUDIT_WRITER,
        OUTBOX,
        CLOCK,
      ],
    },
    {
      provide: PLANNER_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        plans: PurchasePlanRepository,
        settings: SettingsRepository,
      ): PlannerService => new PlannerService(uow, accessControl, plans, settings),
      inject: [UNIT_OF_WORK, ACCESS_CONTROL, PURCHASE_PLAN_REPOSITORY, SETTINGS_REPOSITORY],
    },
    {
      provide: PURCHASE_PLAN_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        plans: PurchasePlanRepository,
        settings: SettingsRepository,
        sales: SaleRepository,
        numbering: NumberingService,
        audit: AuditWriter,
        clock: Clock,
      ): PurchasePlanService =>
        new PurchasePlanService(
          uow,
          accessControl,
          plans,
          settings,
          sales,
          numbering,
          audit,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        ACCESS_CONTROL,
        PURCHASE_PLAN_REPOSITORY,
        SETTINGS_REPOSITORY,
        SALE_REPOSITORY,
        NUMBERING_SERVICE,
        AUDIT_WRITER,
        CLOCK,
      ],
    },
    {
      provide: ADD_LANDED_COST_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        idempotency: IdempotencyStore,
        periods: PeriodGuard,
        costs: LandedCostRepository,
        money: MoneyRepository,
        audit: AuditWriter,
        outbox: Outbox,
        clock: Clock,
      ): AddLandedCostService =>
        new AddLandedCostService(
          uow,
          accessControl,
          idempotency,
          periods,
          costs,
          money,
          audit,
          outbox,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        ACCESS_CONTROL,
        IDEMPOTENCY_STORE,
        PERIOD_GUARD,
        LANDED_COST_REPOSITORY,
        MONEY_REPOSITORY,
        AUDIT_WRITER,
        OUTBOX,
        CLOCK,
      ],
    },
  ],
  // Phase 12.4: sync replays a queued purchase and a queued supplier payment
  // through these very services, so there is one purchase writer and one
  // payment writer in the application (A11, A14, R-D).
  exports: [CREATE_PURCHASE_SERVICE, ADD_LANDED_COST_SERVICE, PAY_SUPPLIER_SERVICE],
})
export class PurchasingModule {}
