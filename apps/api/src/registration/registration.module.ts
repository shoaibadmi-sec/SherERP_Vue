import { Module } from '@nestjs/common';
import type {
  AccessControl,
  AuditWriter,
  CatalogRepository,
  GoogleVerifier,
  IdentityVerifier,
  OtpCodeGenerator,
  OtpRepository,
  PartyRepository,
  PasswordHasher,
  RoleRepository,
  SessionRepository,
  SettingsRepository,
  TenantRepository,
  TokenIssuer,
  UnitOfWork,
  UserIdentifierRepository,
  UserRepository,
} from '@sher/core-application';
import {
  ChangeCredentialsService,
  CompleteRegistrationService,
  GetDashboardSummaryService,
  GetMyAccessService,
  LoginService,
  RegisterWithGoogleService,
  RequestPasswordResetService,
  RequestSignupOtpService,
  ResetPasswordService,
  VerifySignupOtpService,
} from '@sher/core-application';
import type { Clock } from '@sher/shared-utils';

import {
  ACCESS_CONTROL,
  AUDIT_WRITER,
  CATALOG_REPOSITORY,
  CLOCK,
  IDENTITY_VERIFIER,
  OTP_CODE_GENERATOR,
  OTP_REPOSITORY,
  PARTY_REPOSITORY,
  PASSWORD_HASHER,
  GOOGLE_VERIFIER,
  ROLE_REPOSITORY,
  SESSION_REPOSITORY,
  SETTINGS_REPOSITORY,
  TENANT_REPOSITORY,
  TOKEN_ISSUER,
  UNIT_OF_WORK,
  USER_IDENTIFIER_REPOSITORY,
  USER_REPOSITORY,
} from '../infrastructure/tokens';
import { DashboardController } from './dashboard.controller';
import { MeController } from './me.controller';
import { LoginController } from './login.controller';
import { PasswordRecoveryController } from './password-recovery.controller';
import { RegistrationController } from './registration.controller';
import { SecurityController } from './security.controller';
import {
  CHANGE_CREDENTIALS_SERVICE,
  COMPLETE_REGISTRATION_SERVICE,
  GET_DASHBOARD_SUMMARY_SERVICE,
  GET_MY_ACCESS_SERVICE,
  LOGIN_SERVICE,
  REGISTER_WITH_GOOGLE_SERVICE,
  REQUEST_PASSWORD_RESET_SERVICE,
  REQUEST_SIGNUP_OTP_SERVICE,
  RESET_PASSWORD_SERVICE,
  VERIFY_SIGNUP_OTP_SERVICE,
} from './tokens';

@Module({
  controllers: [
    RegistrationController,
    DashboardController,
    MeController,
    LoginController,
    PasswordRecoveryController,
    SecurityController,
  ],
  providers: [
    {
      provide: REQUEST_SIGNUP_OTP_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        otps: OtpRepository,
        identifiers: UserIdentifierRepository,
        codes: OtpCodeGenerator,
        hasher: PasswordHasher,
        verifier: IdentityVerifier,
        audit: AuditWriter,
        clock: Clock,
      ): RequestSignupOtpService =>
        new RequestSignupOtpService(uow, otps, identifiers, codes, hasher, verifier, audit, clock),
      inject: [
        UNIT_OF_WORK,
        OTP_REPOSITORY,
        USER_IDENTIFIER_REPOSITORY,
        OTP_CODE_GENERATOR,
        PASSWORD_HASHER,
        IDENTITY_VERIFIER,
        AUDIT_WRITER,
        CLOCK,
      ],
    },
    {
      provide: VERIFY_SIGNUP_OTP_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        otps: OtpRepository,
        hasher: PasswordHasher,
        clock: Clock,
      ): VerifySignupOtpService => new VerifySignupOtpService(uow, otps, hasher, clock),
      inject: [UNIT_OF_WORK, OTP_REPOSITORY, PASSWORD_HASHER, CLOCK],
    },
    {
      provide: COMPLETE_REGISTRATION_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        otps: OtpRepository,
        identifiers: UserIdentifierRepository,
        tenants: TenantRepository,
        roles: RoleRepository,
        users: UserRepository,
        sessions: SessionRepository,
        catalog: CatalogRepository,
        parties: PartyRepository,
        hasher: PasswordHasher,
        tokens: TokenIssuer,
        audit: AuditWriter,
        clock: Clock,
      ): CompleteRegistrationService =>
        new CompleteRegistrationService(
          uow,
          otps,
          identifiers,
          tenants,
          roles,
          users,
          sessions,
          catalog,
          parties,
          hasher,
          tokens,
          audit,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        OTP_REPOSITORY,
        USER_IDENTIFIER_REPOSITORY,
        TENANT_REPOSITORY,
        ROLE_REPOSITORY,
        USER_REPOSITORY,
        SESSION_REPOSITORY,
        CATALOG_REPOSITORY,
        PARTY_REPOSITORY,
        PASSWORD_HASHER,
        TOKEN_ISSUER,
        AUDIT_WRITER,
        CLOCK,
      ],
    },
    {
      provide: REGISTER_WITH_GOOGLE_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        google: GoogleVerifier,
        identifiers: UserIdentifierRepository,
        tenants: TenantRepository,
        roles: RoleRepository,
        users: UserRepository,
        sessions: SessionRepository,
        catalog: CatalogRepository,
        parties: PartyRepository,
        tokens: TokenIssuer,
        audit: AuditWriter,
        clock: Clock,
      ): RegisterWithGoogleService =>
        new RegisterWithGoogleService(
          uow,
          google,
          identifiers,
          tenants,
          roles,
          users,
          sessions,
          catalog,
          parties,
          tokens,
          audit,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        GOOGLE_VERIFIER,
        USER_IDENTIFIER_REPOSITORY,
        TENANT_REPOSITORY,
        ROLE_REPOSITORY,
        USER_REPOSITORY,
        SESSION_REPOSITORY,
        CATALOG_REPOSITORY,
        PARTY_REPOSITORY,
        TOKEN_ISSUER,
        AUDIT_WRITER,
        CLOCK,
      ],
    },
    {
      provide: LOGIN_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        identifiers: UserIdentifierRepository,
        users: UserRepository,
        sessions: SessionRepository,
        hasher: PasswordHasher,
        tokens: TokenIssuer,
        google: GoogleVerifier,
        audit: AuditWriter,
        clock: Clock,
      ): LoginService =>
        new LoginService(
          uow,
          identifiers,
          users,
          sessions,
          hasher,
          tokens,
          google,
          audit,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        USER_IDENTIFIER_REPOSITORY,
        USER_REPOSITORY,
        SESSION_REPOSITORY,
        PASSWORD_HASHER,
        TOKEN_ISSUER,
        GOOGLE_VERIFIER,
        AUDIT_WRITER,
        CLOCK,
      ],
    },
    {
      provide: REQUEST_PASSWORD_RESET_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        otps: OtpRepository,
        identifiers: UserIdentifierRepository,
        codes: OtpCodeGenerator,
        hasher: PasswordHasher,
        verifier: IdentityVerifier,
        audit: AuditWriter,
        clock: Clock,
      ): RequestPasswordResetService =>
        new RequestPasswordResetService(
          uow,
          otps,
          identifiers,
          codes,
          hasher,
          verifier,
          audit,
          clock,
        ),
      inject: [
        UNIT_OF_WORK,
        OTP_REPOSITORY,
        USER_IDENTIFIER_REPOSITORY,
        OTP_CODE_GENERATOR,
        PASSWORD_HASHER,
        IDENTITY_VERIFIER,
        AUDIT_WRITER,
        CLOCK,
      ],
    },
    {
      provide: RESET_PASSWORD_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        otps: OtpRepository,
        identifiers: UserIdentifierRepository,
        users: UserRepository,
        sessions: SessionRepository,
        hasher: PasswordHasher,
        audit: AuditWriter,
        clock: Clock,
      ): ResetPasswordService =>
        new ResetPasswordService(uow, otps, identifiers, users, sessions, hasher, audit, clock),
      inject: [
        UNIT_OF_WORK,
        OTP_REPOSITORY,
        USER_IDENTIFIER_REPOSITORY,
        USER_REPOSITORY,
        SESSION_REPOSITORY,
        PASSWORD_HASHER,
        AUDIT_WRITER,
        CLOCK,
      ],
    },
    {
      provide: CHANGE_CREDENTIALS_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        users: UserRepository,
        sessions: SessionRepository,
        hasher: PasswordHasher,
        tokens: TokenIssuer,
        audit: AuditWriter,
      ): ChangeCredentialsService =>
        new ChangeCredentialsService(uow, users, sessions, hasher, tokens, audit),
      inject: [
        UNIT_OF_WORK,
        USER_REPOSITORY,
        SESSION_REPOSITORY,
        PASSWORD_HASHER,
        TOKEN_ISSUER,
        AUDIT_WRITER,
      ],
    },
    {
      provide: GET_MY_ACCESS_SERVICE,
      useFactory: (
        uow: UnitOfWork,
        accessControl: AccessControl,
        users: UserRepository,
        tenants: TenantRepository,
        settings: SettingsRepository,
      ): GetMyAccessService =>
        new GetMyAccessService(uow, accessControl, users, tenants, settings),
      inject: [
        UNIT_OF_WORK,
        ACCESS_CONTROL,
        USER_REPOSITORY,
        TENANT_REPOSITORY,
        SETTINGS_REPOSITORY,
      ],
    },
    {
      provide: GET_DASHBOARD_SUMMARY_SERVICE,
      useFactory: (uow: UnitOfWork, tenants: TenantRepository): GetDashboardSummaryService =>
        new GetDashboardSummaryService(uow, tenants),
      inject: [UNIT_OF_WORK, TENANT_REPOSITORY],
    },
  ],
})
export class RegistrationModule {}
