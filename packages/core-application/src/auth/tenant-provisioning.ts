import {
  OWNER_ROLE_CODE,
  SEED_ROLES,
  SEED_UNITS,
  WALK_IN_PARTY_NAME,
} from '@sher/core-contracts';
import type { IdentifierChannel } from '@sher/core-domain';
import type { Clock } from '@sher/shared-utils';
import { addSeconds, Ulid } from '@sher/shared-utils';

import type { CatalogRepository } from '../catalog/catalog-repository';
import type { PartyRepository } from '../parties/party-repository';
import type { AuditWriter } from '../ports/audit-writer';
import type { TenantContext } from '../ports/tenant-context';
import type { TokenIssuer } from '../ports/token-issuer';
import type { Tx } from '../ports/unit-of-work';
import type {
  RoleRepository,
  TenantRepository,
  UserIdentifierRepository,
  UserRepository,
} from './registration-repository';
import type { SessionRepository } from './session-repository';

/**
 * What it means to create a business in SherERP, in one place.
 *
 * Two flows reach here: signup by OTP (`CompleteRegistrationService`) and signup
 * by Google (`RegisterWithGoogleService`, D-07 revised 2026-08-17). They differ
 * only in **how the identifier was proved** — a 6-digit code, or Google's
 * `email_verified` claim — and in which credentials they can set. Everything
 * after the proof is the same rule, and DRY applies to rules (not to lines), so
 * it lives here rather than being written twice and drifting.
 *
 * A plain function, not a service class: it has no state, no dependencies of its
 * own, and no second implementation. The callers already hold every port it
 * needs and pass them in.
 *
 * `tenant_id` is generated by the caller, never read from a request payload
 * (R-C4) — this is the one operation in the system that creates a tenant rather
 * than acting inside one.
 */
export interface ProvisionTenantDeps {
  readonly tenants: TenantRepository;
  readonly roles: RoleRepository;
  readonly users: UserRepository;
  readonly identifiers: UserIdentifierRepository;
  readonly sessions: SessionRepository;
  readonly catalog: CatalogRepository;
  readonly parties: PartyRepository;
  readonly tokens: TokenIssuer;
  readonly audit: AuditWriter;
  readonly clock: Clock;
}

export interface ProvisionTenantCommand {
  readonly businessName: string;
  readonly username: string;
  readonly identifier: string;
  readonly channel: IdentifierChannel;
  /**
   * NULL on a Google-created account: Google is the only way in until the owner
   * sets a password through forgot-password (§5.3). A placeholder hash here
   * would be a password nobody chose, so the column stays honest instead.
   */
  readonly passwordHash: string | null;
  /** NULL on a Google-created account, for the same reason. */
  readonly pinHash: string | null;
  /** How the identifier was proved, recorded on the audit event. */
  readonly verifiedBy: string;
}

export interface ProvisionedTenant {
  readonly accessToken: string;
  readonly refreshToken: string;
  readonly username: string;
}

/** 30 days (§5.3), matching the sessions a login mints. */
const REFRESH_TOKEN_SECONDS = 30 * 24 * 60 * 60;

export async function provisionTenant(
  tx: Tx,
  ctx: TenantContext,
  deps: ProvisionTenantDeps,
  command: ProvisionTenantCommand,
): Promise<ProvisionedTenant> {
  await deps.tenants.insert(tx, ctx, {
    id: ctx.tenantId,
    name: command.businessName,
    timezone: ctx.timezone,
  });

  // §5.26 ships all six roles with every tenant, not just the one the founder
  // holds — otherwise the first person hired could only be made an Owner.
  let ownerRoleId: string | null = null;
  for (const seed of SEED_ROLES) {
    const roleId = Ulid.generate(deps.clock);
    if (seed.code === OWNER_ROLE_CODE) ownerRoleId = roleId;

    await deps.roles.insertSystemRole(tx, ctx, {
      id: roleId,
      code: seed.code,
      name: seed.name,
    });
    for (const permission of seed.permissions) {
      await deps.roles.grant(tx, ctx, roleId, permission);
    }
  }
  if (ownerRoleId === null) throw new Error('SEED_ROLES must contain the Owner role');

  await deps.users.insert(tx, ctx, {
    id: ctx.userId,
    roleId: ownerRoleId,
    username: command.username,
    displayName: command.username,
    email: command.channel === 'EMAIL' ? command.identifier : null,
    phone: command.channel === 'PHONE' ? command.identifier : null,
    passwordHash: command.passwordHash,
    pinHash: command.pinHash,
  });
  await deps.identifiers.claim(tx, {
    id: Ulid.generate(deps.clock),
    identifier: command.identifier,
    channel: command.channel,
    tenantId: ctx.tenantId,
    userId: ctx.userId,
  });

  // D-10's units of measure. A product's base unit is mandatory (§5.5), so a
  // business created with an empty unit list is a business that cannot add its
  // first product. They are ordinary rows from here on — renameable and
  // removable like any other.
  for (const name of SEED_UNITS) {
    await deps.catalog.insertUnit(tx, ctx, { id: Ulid.generate(deps.clock), name });
  }

  /*
   * D-02's walk-in customer: "one real, `system_reserved` party exempt from the
   * constraint". Created with the business, because a fully paid guest sale in
   * Phase 6 must point at a real party — and a shop whose first sale created it
   * on the fly would have two tills racing to create it.
   *
   * No phone, which is exactly the exemption D-02 grants it, and no customer
   * phone key, so it never occupies a number a real customer might use.
   */
  await deps.parties.insert(tx, ctx, {
    id: Ulid.generate(deps.clock),
    name: WALK_IN_PARTY_NAME,
    roles: ['CUSTOMER'],
    phone: null,
    address: null,
    guardianName: null,
    nid: null,
    email: null,
    notes: null,
    customerGroupId: null,
    creditLimitMinor: null,
    isSystemReserved: true,
  });

  await deps.audit.append(tx, ctx, {
    entityType: 'tenant',
    entityId: ctx.tenantId,
    action: 'CREATE',
    before: null,
    after: {
      name: command.businessName,
      username: command.username,
      channel: command.channel,
      verifiedBy: command.verifiedBy,
      // Worth recording: an account with no password is a different thing to
      // audit later than one that has always had a full credential set.
      hasPassword: command.passwordHash === null ? 'NO' : 'YES',
      hasPin: command.pinHash === null ? 'NO' : 'YES',
    },
    source: 'API',
  });

  // Signing up leaves you signed in, on the same footing as a login: an access
  // token plus a server-stored session that "log out" can revoke.
  const refreshToken = deps.tokens.issueRefreshToken();
  await deps.sessions.create(tx, {
    id: Ulid.generate(deps.clock),
    tenantId: ctx.tenantId,
    userId: ctx.userId,
    tokenHash: deps.tokens.hashRefreshToken(refreshToken),
    expiresAt: addSeconds(deps.clock.now(), REFRESH_TOKEN_SECONDS),
  });

  return {
    accessToken: deps.tokens.issueAccessToken(ctx),
    refreshToken,
    username: command.username,
  };
}
